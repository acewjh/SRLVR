def _game_from_sample(sample: Sample) -> GameRef:
    meta = sample.metadata or {}
    path = meta.get("game_path")
    if not path:
        raise ValueError(
            "ALFWorld sample is missing metadata['game_path']; the prompt data must be "
            "produced by tasks.alfworld.v1.data_prepare (see --prompt-data)."
        )
    return GameRef(
        game_id=meta.get("game_id", path),
        path=path,
        task_type=meta.get("task_type", "unknown"),
        split=meta.get("split", "train"),
    )


async def _run_group(
    args: Namespace,
    state: GenerateState,
    group: list[Sample],
    sampling_params: dict,
    trajectories_out: list[Trajectory] | None = None,
) -> list[Sample]:
    """All G episodes of one task, then one shared reward assignment."""
    mode = config.privilege_mode(args)
    gap = config.future_gap(args)
    game = _game_from_sample(group[0])
    base_seed = int(getattr(args, "rollout_seed", 0) or 0)

    async def one(sample: Sample, offset: int):
        params = dict(sampling_params)
        params["sampling_seed"] = base_seed + int(sample.index or 0) + offset
        return await run_episode(args, state.tokenizer, game, params, seed=params["sampling_seed"])

    async with state.semaphore:
        results = await asyncio.gather(*[one(s, i) for i, s in enumerate(group)])

    for sample, (trajectory, layout, _metrics) in zip(group, results, strict=True):
        sample.tokens = list(layout.tokens)
        sample.response_length = layout.response_length
        sample.response = ""
        sample.loss_mask = list(layout.loss_mask)
        sample.turn_ids = list(layout.turn_ids)
        sample.rollout_log_probs = list(layout.rollout_log_probs)
        sample.reward = trajectory.terminal_reward
        sample.status = Sample.Status.TRUNCATED if trajectory.truncated else Sample.Status.COMPLETED

        sample.metadata["trajectory"] = trajectory.to_dict()
        sample.metadata["turn_spans"] = [list(s) for s in layout.turn_spans]
        sample.metadata["num_turns"] = trajectory.num_turns
        sample.metadata["invalid_action_count"] = trajectory.invalid_action_count
        if mode != MODE_NONE:
            views, plens, tlens = build_episode_hpi_views(state.tokenizer, trajectory, layout, mode, gap)
            sample.metadata["hpi_views"] = views
            sample.metadata["hpi_prompt_lengths"] = plens
            sample.metadata["hpi_target_lengths"] = tlens
        if trajectories_out is not None:
            trajectories_out.append(trajectory)

    return group


def generate_rollout(args: Namespace, rollout_id: int, data_source, evaluation: bool = False):
    """Custom rollout entry point (see ``slime.ray.rollout.call_rollout_fn``).

    Doubles as ``--eval-function-path``: slime calls the same callable with
    ``evaluation=True`` and expects a ``RolloutFnEvalOutput`` instead.
    """
    from slime.utils.async_utils import run

    if evaluation:
        return run(_eval_async(args, rollout_id))
    return run(_generate_rollout_async(args, rollout_id, data_source, evaluation))


