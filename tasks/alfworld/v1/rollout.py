def load_eval_games(path: str) -> list[GameRef]:
    """Read one of this harness's eval JSONLs (see ``data_prepare``).

    Deliberately not routed through slime's ``Dataset``: the records carry no
    prompt text (the rollout renders every turn), so all that is needed is the
    game identity, and parsing the file directly removes a dependency on the
    dataset/chat-template configuration being consistent between train and eval.
    """
    import json

    games: list[GameRef] = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            record = json.loads(line)
            meta = record.get("metadata") or {}
            if not meta.get("game_path"):
                raise ValueError(f"eval record in {path} is missing metadata['game_path']")
            games.append(
                GameRef(
                    game_id=meta.get("game_id", meta["game_path"]),
                    path=meta["game_path"],
                    task_type=meta.get("task_type", "unknown"),
                    split=meta.get("split", "unknown"),
                )
            )
    return games


async def _eval_async(args: Namespace, rollout_id: int):
    """One episode per eval game, reported in slime's eval-data shape.

    ``data[dataset_key] = {"rewards": [...], "samples": [...], "truncated": [...]}``
    -- see ``slime.ray.rollout._log_eval_rollout_data``.
    """
    from slime.rollout.base_types import RolloutFnEvalOutput

    state = GenerateState(args)
    sampling_params = dict(state.sampling_params)
    results: dict[str, dict] = {}

    for dataset_cfg in getattr(args, "eval_datasets", []) or []:
        key = getattr(dataset_cfg, "name", None) or str(dataset_cfg.path)
        games = load_eval_games(dataset_cfg.path)
        per_game: list[Sample] = []
        semaphore = asyncio.Semaphore(max(1, int(os.environ.get("ALFWORLD_EVAL_CONCURRENCY", "8"))))

        async def one(index: int, game: GameRef):
            async with semaphore:
                params = dict(sampling_params)
                params["sampling_seed"] = int(getattr(args, "rollout_seed", 0) or 0) + index
                trajectory, _layout, _metrics = await run_episode(
                    args, state.tokenizer, game, params, seed=params["sampling_seed"]
                )
            sample = Sample(index=index, prompt=trajectory.task_description)
            sample.reward = trajectory.terminal_reward
            sample.response = ""
            sample.status = (
                Sample.Status.TRUNCATED if trajectory.truncated else Sample.Status.COMPLETED
            )
            sample.metadata["trajectory"] = trajectory.to_dict()
            sample.metadata["num_turns"] = trajectory.num_turns
            sample.metadata["invalid_action_count"] = trajectory.invalid_action_count
            return sample

        per_game = await asyncio.gather(*[one(i, g) for i, g in enumerate(games)])

        results[key] = {
            "rewards": [float(s.reward) for s in per_game],
            "samples": list(per_game),
            "truncated": [1 if s.status == Sample.Status.TRUNCATED else 0 for s in per_game],
        }
        logger.info(
            "[alfworld-eval] %s: n=%d success_rate=%.4f",
            key,
            len(per_game),
            sum(float(s.reward) for s in per_game) / max(len(per_game), 1),
        )

    return RolloutFnEvalOutput(data=results)


async def _generate_rollout_async(args: Namespace, rollout_id: int, data_source, evaluation: bool):
    # slime.rollout.sglang_rollout does not export an abort helper; the repo's own
    # bounded implementation lives in tasks.math.math_rollout (same choice grpo_rollout made).
    from tasks.math.math_rollout import _abort

    state = GenerateState(args)
    sampling_params = dict(state.sampling_params)
    target_data_size = args.rollout_batch_size  # number of PROMPTS (tasks)

    data: list[list[Sample]] = []
    ready: list[list[Sample]] = []
    pendings: set[asyncio.Task] = set()
    metrics_acc: dict[str, float] = {}
    n_episodes = 0

    while len(data) < target_data_size:
        while len(ready) + len(pendings) + len(data) < target_data_size:
            samples = (
                data_source.get_samples(args.over_sampling_batch_size)
                if hasattr(data_source, "get_samples")
                else data_source(args.over_sampling_batch_size)
            )
            for group in samples:
                pendings.add(asyncio.create_task(_run_group(args, state, group, sampling_params)))

        done, pendings = await asyncio.wait(pendings, return_when=asyncio.FIRST_COMPLETED)
        for task in done:
            group = task.result()
            ready.append(group)
            for sample in group:
                meta = sample.metadata
                metrics_acc["turns"] = metrics_acc.get("turns", 0.0) + meta.get("num_turns", 0)
                metrics_acc["success"] = metrics_acc.get("success", 0.0) + float(sample.reward or 0.0)
                metrics_acc["invalid"] = metrics_acc.get("invalid", 0.0) + meta.get("invalid_action_count", 0)
                n_episodes += 1
        while ready and len(data) < target_data_size:
            data.append(ready.pop(0))

    await _abort(args, state)
    state.reset()

    data = sorted(data, key=lambda group: group[0].index)
    denom = max(n_episodes, 1)
    metrics = {
        "rollout/mean_turns": metrics_acc.get("turns", 0.0) / denom,
        "rollout/success_rate": metrics_acc.get("success", 0.0) / denom,
        "rollout/mean_invalid_actions": metrics_acc.get("invalid", 0.0) / denom,
        "rollout/group_size": sum(len(g) for g in data) / max(len(data), 1),
    }
    return RolloutFnTrainOutput(samples=data, metrics=metrics)
