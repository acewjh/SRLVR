# Episode
# ---------------------------------------------------------------------------


async def run_episode(
    args: Namespace,
    tokenizer,
    game: GameRef,
    sampling_params: dict,
    seed: int,
) -> tuple[Trajectory, EpisodeLayout, dict]:
    """Run one ALFWorld episode with the Qwen3 think/act loop.

    Environment stepping is pushed to a worker thread: textworld is blocking CPU
    work, and running it inline would stall every other in-flight episode sharing
    the event loop.
    """
    max_t = config.max_turns(args)

    env = await asyncio.to_thread(AlfWorldEnv, game, max(max_t, DEFAULT_MAX_STEPS))
    try:
        result = await asyncio.to_thread(env.reset)
        task_description = env.task_description

        trajectory = Trajectory(
            task_id=game.game_id,
            task_type=game.task_type,
            split=game.split,
            task_description=task_description,
            seed=seed,
            success=False,
            terminal_reward=0.0,
            num_turns=0,
            truncated=False,
            invalid_action_count=0,
        )

        current = result
        action_history: list[str] = []
        view = _make_view(task_description, current, action_history)
        prompt_ids = build_turn_prompt_ids(tokenizer, view)
        layout = EpisodeLayout(prefix_ids=prompt_ids)

        generated_tokens_total = 0

        for turn in range(max_t):
            output = await _generate_tokens(args, prompt_ids, sampling_params)
            y_ids = list(output["token_ids"])
            y_log_probs = list(output["log_probs"])
            _strip_stop_token(y_ids, y_log_probs, tokenizer)
            y_text = output["text"]
            generated_tokens_total += len(y_ids)

            truncated_turn = output["finish_reason"] == "length"
            parsed = parse_turn_output(y_text, current.admissible_actions, truncated=truncated_turn)

            layout.turns.append((list(prompt_ids), list(y_ids), view))
            layout.add_generation(turn, y_ids, y_log_probs)

            # ---- environment transition -------------------------------------
            if parsed.is_valid:
                step_result = await asyncio.to_thread(env.step, parsed.action)
                action_history.append(parsed.action)
                next_observation = step_result.observation
                done = bool(step_result.done)
                won = bool(step_result.won)
            else:
                # Inadmissible / malformed: do NOT consume an environment step, so
                # `max_turns` bounds real interaction and the invalid-action count
                # stays a clean diagnostic. The transition is recorded as a no-op
                # so the transition index stays aligned with the turn index.
                #
                # The rejection is fed BACK into the next turn's observation. Without
                # it the model sees a byte-identical situation and has no way to know
                # its action was rejected, so it repeats the same mistake for the
                # rest of the episode -- measured on the first real run, 21% of turns
                # were inadmissible and every episode then stalled to the turn cap.
                # The original observation is appended so the room state is not lost.
                trajectory.invalid_action_count += 1
                step_result = None
                attempted = parsed.raw_action or "(no action)"
                next_observation = (
                    f"Your previous action {attempted!r} was rejected: it is not one of the "
                    "admissible actions. You are still in the same situation. Choose one of "
                    "the admissible actions listed below, copied exactly.\n\n"
                    f"{current.observation}"
                )
                done = False
                won = False

            trajectory.turns.append(
                TurnRecord(
                    turn_idx=turn,
                    observation=current.observation,
                    admissible_actions=list(current.admissible_actions),
                    student_prompt="",
                    prompt_token_ids=list(prompt_ids),
                    generated_token_ids=list(y_ids),
                    generated_text=y_text,
                    think_text=parsed.think_text,
                    action_text=parsed.action or "",
                    action_valid=parsed.is_valid,
                    parse_status=parsed.status.value,
                    next_observation=next_observation,
                    env_reward=terminal_reward(won) if done else 0.0,
                    done=done,
                )
            )
            trajectory.num_turns = turn + 1

            if done:
                trajectory.success = won
                break
            if turn + 1 >= max_t:
                trajectory.truncated = True
                break

            # An invalid turn does not step the environment, so the observation is
            # unchanged. `step_result` is None in that case -- keep the previous
            # result rather than overwriting `current` with None.
            if step_result is not None:
                current = step_result
            view = _make_view(task_description, current, action_history)
            prompt_ids = build_turn_prompt_ids(tokenizer, view)
            layout.add_prompt(prompt_ids)

        trajectory.terminal_reward = terminal_reward(trajectory.success)
    finally:
        await asyncio.to_thread(env.close)

    metrics = {
        "turns": trajectory.num_turns,
        "generated_tokens": generated_tokens_total,
        "invalid_actions": trajectory.invalid_action_count,
        "success": int(trajectory.success),
        "truncated": int(trajectory.truncated),
    }
    return trajectory, layout, metrics


def _make_view(task_description: str, result, action_history: list[str]) -> TaskView:
    return TaskView(
        task_description=task_description,
        current_observation=result.observation,
        admissible_actions=list(result.admissible_actions),
        action_history=list(action_history),
    )


# ---------------------------------------------------------------------------
# HPI view construction (post-episode)
# ---------------------------------------------------------------------------


def build_episode_hpi_views(
    tokenizer,
    trajectory: Trajectory,
    layout: EpisodeLayout,
    mode: str,
    gap: int,
) -> tuple[list[list[int]], list[int], list[int]]:
    """Build the (full, control) teacher views for every turn of a finished episode.

    Returns ``(views, prompt_lengths, target_lengths)`` in the interleaved order
    ``[full_0, ctrl_0, full_1, ctrl_1, ...]`` -- exactly the layout
    ``train_data.convert_samples_to_train_data`` forwards as ``hpi_views``.

    The control view reuses the student's stored prompt ids verbatim, so the pair
    differs by the privileged block and nothing else. Both views are teacher-forced
    on the same ``y_t`` ids.

    Returns empty lists for ``mode="none"`` -- ``build_hpi_privilege`` yields an
    empty block there, and an empty block would make full == control (``e_t == 0``
    identically), so the caller is expected to skip the HPI path entirely.
    """
    if mode == MODE_NONE:
        return [], [], []

    views: list[list[int]] = []
    prompt_lengths: list[int] = []
    target_lengths: list[int] = []

    for turn_index, (prompt_ids, y_ids, view) in enumerate(layout.turns):
        privilege_text = build_hpi_privilege(trajectory, turn_index, mode, gap)
        if not privilege_text:
            raise RuntimeError(
                f"mode={mode!r} produced an empty privilege block for turn {turn_index}; "
                "a full view identical to the control view would make e_t identically 0."
            )
        full_prefix = build_privileged_prompt_ids(tokenizer, view, privilege_text)
        views.append(list(full_prefix) + list(y_ids))
        views.append(list(prompt_ids) + list(y_ids))
        prompt_lengths.extend([len(full_prefix), len(prompt_ids)])
        target_lengths.extend([len(y_ids), len(y_ids)])

    return views, prompt_lengths, target_lengths


