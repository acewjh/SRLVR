DEFAULT_MAX_TURNS = config.DEFAULT_MAX_TURNS

_DEFAULT_TIMEOUT_S = 900


def _engine_url(args: Namespace) -> str:
    return os.environ.get("OPSD_ENGINE_URL") or (
        f"http://{args.sglang_router_ip}:{args.sglang_router_port}"
    )


# ---------------------------------------------------------------------------
# SGLang interaction
# ---------------------------------------------------------------------------


async def _generate_tokens(args: Namespace, prompt_ids: list[int], sampling_params: dict) -> dict:
    """One token-in / token-out engine call with bounded retries."""
    payload = {"input_ids": prompt_ids, "sampling_params": sampling_params, "return_logprob": True}
    engine_url = _engine_url(args)
    timeout_s = float(os.environ.get("OPSD_ROLLOUT_TIMEOUT_S", str(_DEFAULT_TIMEOUT_S)))
    attempts = max(1, int(os.environ.get("OPSD_ROLLOUT_ATTEMPTS", "3")))

    last_exc: Exception | None = None
    for attempt in range(attempts):
        try:
            output = await asyncio.wait_for(post(f"{engine_url}/generate", payload), timeout=timeout_s)
            break
        except (asyncio.TimeoutError, TimeoutError) as exc:  # noqa: PERF203
            last_exc = exc
            logger.warning(
                "[alfworld] /generate exceeded %.0fs (attempt %d/%d) engine=%s -- retrying",
                timeout_s,
                attempt + 1,
                attempts,
                engine_url,
            )
    else:
        raise RuntimeError(
            f"/generate did not return after {attempts} attempts x {timeout_s}s ({engine_url})"
        ) from last_exc

    meta = output.get("meta_info", {}) or {}
    entries = meta.get("output_token_logprobs") or []
    return {
        "token_ids": [int(item[1]) for item in entries],
        "log_probs": [float(item[0]) for item in entries],
        "text": output.get("text", ""),
        "finish_reason": (meta.get("finish_reason") or {}).get("type"),
    }


def _strip_stop_token(token_ids: list[int], log_probs: list[float], tokenizer) -> int:
    """Truncate trailing stop tokens in place; return the new length.

    The chat template re-adds ``<|im_end|>`` when the *next* turn renders the
    assistant history message, so keeping it would double it. Log-probs are cut
    by the same amount so the two arrays stay index-aligned.
    """
    stop_ids = set(getattr(tokenizer, "all_special_ids", None) or [])
    eos = getattr(tokenizer, "eos_token_id", None)
    if eos is not None:
        stop_ids.add(eos)
    kept = len(token_ids)
    while kept and token_ids[kept - 1] in stop_ids:
        kept -= 1
    del token_ids[kept:]
    del log_probs[kept:]
    return kept


