@dataclass
class EpisodeLayout:
    """Training sequence + per-turn records for one episode."""

    prefix_ids: list[int]
    tokens: list[int] = field(default_factory=list)
    loss_mask: list[int] = field(default_factory=list)
    turn_ids: list[int] = field(default_factory=list)
    #: SGLang sampling log-probs, aligned to the *response* region. Prompt
    #: positions carry a dummy 0.0 (they are masked out of the loss anyway); the
    #: array must be response-length because that is what slime concatenates into
    #: `rollout_log_probs` for the PPO ratio.
    rollout_log_probs: list[float] = field(default_factory=list)
    #: response-relative (start, end) of each turn's generated tokens.
    turn_spans: list[tuple[int, int]] = field(default_factory=list)
    #: per turn: (prompt_token_ids, generated_token_ids, TaskView)
    turns: list[tuple[list[int], list[int], TaskView]] = field(default_factory=list)

    def __post_init__(self) -> None:
        self.prefix_len = len(self.prefix_ids)
        self.tokens = list(self.prefix_ids)

    def add_prompt(self, prompt_ids: list[int]) -> None:
        self.tokens.extend(prompt_ids)
        self.loss_mask.extend([0] * len(prompt_ids))
        self.turn_ids.extend([-1] * len(prompt_ids))
        self.rollout_log_probs.extend([0.0] * len(prompt_ids))

    def add_generation(self, turn_index: int, token_ids: list[int], log_probs: list[float]) -> tuple[int, int]:
        start = len(self.tokens) - self.prefix_len
        self.tokens.extend(token_ids)
        self.loss_mask.extend([1] * len(token_ids))
        self.turn_ids.extend([turn_index] * len(token_ids))
        self.rollout_log_probs.extend(log_probs)
        end = len(self.tokens) - self.prefix_len
        self.turn_spans.append((start, end))
        return start, end

    @property
    def response_length(self) -> int:
        return len(self.tokens) - self.prefix_len

    @property
    def response_tokens(self) -> list[int]:
        return self.tokens[self.prefix_len :]


