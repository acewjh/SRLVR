"""ALFWorld multi-turn rollout for slime (``--rollout-function-path``).

Hook choice
-----------
``--custom-generate-function-path`` was rejected: it is only reachable from the
*stock* sglang rollout, which would then also own reward application and data
conversion and fight with this harness's custom convert/loss.
``--rollout-function-path`` is the hook the rest of this repo already uses
(``tasks.math.math_rollout``, ``math_opsd.grpo_rollout``), so this module follows
that contract exactly: ``generate_rollout(args, rollout_id, data_source,
evaluation=False)`` returning a ``RolloutFnTrainOutput``.

Sequence layout (the load-bearing decision)
-------------------------------------------
The student context at turn ``t`` is ``h_t`` = task + past ACTIONS + past
OBSERVATIONS + current admissible actions. Past ``<think>`` blocks are excluded
by contract, and Qwen3's own chat template independently strips them from
assistant history -- so ``h_{t+1}`` is **not** a token-level extension of
``h_t + y_t``. Chaining turns into one causal sequence would train on contexts
the engine never saw.

Each episode is therefore laid out as per-turn segments::

    tokens    = prompt_0 | y_0 | prompt_1 | y_1 | prompt_2 | y_2 | ...
    loss_mask =   0 ...  |  1  |   0 ...  |  1  |   0 ...  |  1  | ...

Every ``y_t`` is immediately preceded by exactly ``prompt_t``, so a causal
forward over this layout conditions each generated token on precisely the context
the engine used. ``loss_mask`` is 0 on every prompt segment, so segment-boundary
discontinuities carry no gradient.

The cost is O(T^2) growth in context. It is bounded by ``--alfworld-max-turns``
and by capping the rendered action history (``prompts.DEFAULT_ACTION_HISTORY``).
The teacher uses the same layout, so the comparison stays apples-to-apples.

Two-pass HPI (why the privilege is attached post-episode)
---------------------------------------------------------
``future_outcome`` privilege depends on the *whole* episode, including turns that
have not happened yet while turn ``t`` is being generated. The online path can
therefore only ever build ``outcome_only``. Rather than special-case it, view
construction happens once, after the episode finishes, in
:func:`build_episode_hpi_views`, for every mode. This mirrors the reference
implementation's move of privileged scoring out of the per-turn loop, and keeps
the rollout itself free of any teacher computation.

Alignment guarantees
--------------------
* ``y_t`` token ids are stored exactly as returned by the engine -- never decoded
  and re-encoded.
* ``prompt_t`` token ids are stored exactly as sent to the engine, so the
  teacher's control view is byte-identical to the student's context for free.
* ``loss_mask == 1`` iff the token was generated by the model.
* ``turn_ids`` carries the turn index per response token, which is how the loss
  maps a view back onto its span without any extra slime plumbing.
"""

